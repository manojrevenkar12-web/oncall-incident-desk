package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/manojrevenkar12-web/oncall-incident-desk/internal/lab"
)

const (
	startMark = "<!-- results:start -->"
	endMark   = "<!-- results:end -->"
)

func load(root, which string) (*lab.Report, error) {
	b, err := os.ReadFile(filepath.Join(root, "reports", which+".json"))
	if err != nil {
		return nil, err
	}
	var r lab.Report
	return &r, json.Unmarshal(b, &r)
}

func ci(s lab.Stat, f string) string {
	v := fmt.Sprintf(f, s.Value)
	if s.Lo == s.Hi {
		return v
	}
	return fmt.Sprintf("%s <sub>%s–%s</sub>", v, fmt.Sprintf(f, s.Lo), fmt.Sprintf(f, s.Hi))
}

func pct(s lab.Stat) string {
	if s.Lo == s.Hi {
		return fmt.Sprintf("%.1f%%", 100*s.Value)
	}
	return fmt.Sprintf("%.1f%% <sub>%.1f–%.1f</sub>", 100*s.Value, 100*s.Lo, 100*s.Hi)
}

func table(r *lab.Report, ablations bool) string {
	var b strings.Builder
	b.WriteString("| Design | Outages acknowledged in time | First page (median min) | Acknowledged (median min) | False pages / week | …at night | Pages per outage | Public outages announced | First post (median min) | Bad claims / 100 posts |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|\n")
	for _, d := range r.Designs {
		if d.Ablation != ablations {
			continue
		}
		s := d.Stats
		name := d.Label
		if d.Name == "desk" {
			name = "**" + name + "**"
		}
		fmt.Fprintf(&b, "| %s | %s | %.0f | %s | %s | %.1f | %.2f | %s | %.0f | %s |\n", name, pct(s["recall"]),
			s["ttp_median"].Value, ci(s["mtta_median"], "%.1f"), ci(s["false_pages_per_week"], "%.1f"),
			s["night_false_pages_per_week"].Value, s["pages_per_outage"].Value, pct(s["notice_coverage"]),
			s["notice_median"].Value, ci(s["bad_claims_per_100_posts"], "%.1f"))
	}
	return b.String()
}

func gates(r *lab.Report) string {
	var b strings.Builder
	pass := 0
	for _, g := range r.Gates {
		if g.Pass {
			pass++
		}
	}
	fmt.Fprintf(&b, "%d of %d gates pass.\n\n| Gate | Rule | Got | |\n|---|---|---|---|\n", pass, len(r.Gates))
	for _, g := range r.Gates {
		mark := "pass"
		if !g.Pass {
			mark = "**fail**"
		}
		fmt.Fprintf(&b, "| %s | %s %.3g | %.3g | %s |\n", g.Name, g.Rule, g.Want, g.Got, mark)
	}
	return b.String()
}

func checker(r *lab.Report) string {
	c := r.Checker
	var b strings.Builder
	fmt.Fprintf(&b, "%d drafts, %d carrying an error the stand-in model put there. The checker refused %d of them (%.1f%%) and refused %d clean drafts (%.1f%% of clean ones).\n\n",
		c.Drafts, c.WithError, c.Caught, 100*c.Recall, c.CleanRejected, 100*c.FalseRejectRate)
	b.WriteString("| Error in the draft | Drafts | Refused |\n|---|---|---|\n")
	names := map[string]string{"internal_detail": "Internal detail (host, IP, error code)", "recovery_promise": "Promised a recovery time",
		"unaffected_component": "Named a component that was working", "unconfirmed_cause": "Stated a cause nobody confirmed"}
	rows := append([]lab.KindRow(nil), c.ByKind...)
	sort.Slice(rows, func(i, j int) bool { return rows[i].Kind < rows[j].Kind })
	for _, k := range rows {
		fmt.Fprintf(&b, "| %s | %d | %d |\n", names[k.Kind], k.Injected, k.Caught)
	}
	if len(c.Through) > 0 {
		b.WriteString("\nDrafts that got through with an error in them:\n\n")
		for _, e := range c.Through {
			fmt.Fprintf(&b, "- “%s” (%s)\n", e.Text, strings.Join(e.Injected, ", "))
		}
	}
	return b.String()
}

func readme(root string) error {
	dev, err := load(root, "dev")
	if err != nil {
		return fmt.Errorf("run `go run ./cmd/desk study -world dev` first: %w", err)
	}
	held, herr := load(root, "heldout")
	var b strings.Builder
	b.WriteString(startMark + "\n")
	b.WriteString("_Generated by `go run ./cmd/desk readme` from `reports/dev.json` and `reports/heldout.json`. Do not edit by hand._\n\n")
	fmt.Fprintf(&b, "Each world is %d seeds of %d days: %d services, %d checks run every minute from each location. Brackets are 95%% bootstrap intervals over seeds.\n\n",
		len(dev.Seeds), dev.Days, dev.Services, dev.Checks)
	b.WriteString("### Held-out world (ran once)\n\n")
	if herr != nil {
		b.WriteString("Not run yet. `make heldout` runs it once and locks it.\n\n")
	} else {
		fmt.Fprintf(&b, "Seeds %d–%d, %d locations, more blips, flakes, duplicates and degraded outages, slower nights, and status-post errors worded in ways the dev world never used. %d real outages, %d location blips.\n\n",
			held.Seeds[0], held.Seeds[len(held.Seeds)-1], held.Locations, held.Truth.Outages, held.Truth.Blips)
		b.WriteString(gates(held) + "\n")
		b.WriteString(table(held, false) + "\n")
		b.WriteString("Ablations (the desk with one piece taken out):\n\n" + table(held, true) + "\n")
		b.WriteString("**The claim checker on held-out wording.** " + checker(held) + "\n")
	}
	b.WriteString("### Dev world\n\n")
	fmt.Fprintf(&b, "Seeds %d–%d, %d real outages (median %.0f minutes, %.0f%% at night), %d location blips.\n\n",
		dev.Seeds[0], dev.Seeds[len(dev.Seeds)-1], dev.Truth.Outages, dev.Truth.MedianMin, 100*dev.Truth.NightShare, dev.Truth.Blips)
	b.WriteString(gates(dev) + "\n")
	b.WriteString(table(dev, false) + "\n")
	b.WriteString("Ablations:\n\n" + table(dev, true) + "\n")
	b.WriteString("**The claim checker.** " + checker(dev))
	b.WriteString(endMark)
	path := filepath.Join(root, "README.md")
	old, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(old)
	i, j := strings.Index(s, startMark), strings.Index(s, endMark)
	if i < 0 || j < i {
		return fmt.Errorf("README.md has no %s … %s block", startMark, endMark)
	}
	s = s[:i] + b.String() + s[j+len(endMark):]
	return os.WriteFile(path, []byte(s), 0o644)
}
